import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { hostImport, manifest } from './desktop-host.mjs';
import { ChatGptWebAdapter } from '../src/host-adapter.ts';
import { DEFAULT_CONFIG } from '../src/config.ts';
import { LlmAdapter, LlmRuntime, BlockAssembler } from '@deepseek-ai/dsh-llm';
const { Context } = await hostImport('cordis');
const { evaluatePluginCompatibility, getDshRuntimeVersion, isNativeConfigSchema } = await hostImport('dsh-app-boot');
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
assert.equal(getDshRuntimeVersion(), '0.2.1-rc.3');
assert.equal(evaluatePluginCompatibility(pkg), undefined, 'real gate accepts without exemption');
assert.equal(evaluatePluginCompatibility({ ...pkg, peerDependencies: { '@deepseek-ai/dsh-llm': '^0.1.7-rc.2' } }).exempted, false, 'old peer truly rejected');
assert.equal(evaluatePluginCompatibility(pkg, {}, '0.2.2')?.exempted, false, 'unverified versions remain excluded');
assert.equal(pkg.engines.dsh, undefined, 'no engines override hiding peer mismatch');
assert.equal(JSON.stringify(pkg).includes('workspace:'), false);
const plugin = await import('../lib/index.js');
assert.equal(isNativeConfigSchema(plugin.Config), true);
const ctx = new Context();
const llm = new LlmRuntime(ctx);
const fiber = ctx.plugin({ name: 'offline-desktop-contract', apply(local) {
  plugin.apply({ llm, effect: local.effect.bind(local), logger: { info() {} } }, DEFAULT_CONFIG);
} });
await new Promise(resolve => setImmediate(resolve));
assert.equal(llm.listProviders()[0].id, 'chatgpt-web');
assert.equal((await llm.listModels('chatgpt-web'))[0].id, 'chatgpt-free');
assert.deepEqual((await llm.resolveModelInfo('chatgpt-web', 'chatgpt-free')).inputModalities, ['text']);
await fiber.dispose();
assert.deepEqual(llm.listProviders(), [], 'actual Cordis disposal unregisters built plugin');
const auth = { version: 1, accessToken: 'offline-placeholder', cookieHeader: null, dataBuild: '', userAgent: '', languages: [], planType: null, capturedAt: 0, lastOkAt: null };
const config = { ...DEFAULT_CONFIG, minIntervalMs: 0, maxIntervalMs: 0 };
const adapter = new ChatGptWebAdapter(config, { loadAuth: async () => auth, runTurn: async input => {
  const text = 'visible<tool_call>{"name":"read","arguments":{"path":"a"}}</tool_call>';
  const frame = JSON.stringify({ v: { message: { id: 'offline-message', author: { role: 'assistant' }, content: { parts: [text] }, status: 'finished_successfully' } } });
  input.onFrame(frame);
  return { status: 200, frames: [frame], sawDone: true, failure: null, errorBody: null, totalMs: 1, ttfbMs: 1 };
} });
assert.ok(adapter instanceof LlmAdapter);
const handle = llm.registerAdapter(['chatgpt-web'], adapter);
assert.throws(() => llm.registerAdapter(['chatgpt-web'], adapter), /already registered/);
const call = await llm.prepareCall({ provider: 'chatgpt-web', model: 'chatgpt-free' });
assert.equal(call.config.maxTokens, 2048);
assert.deepEqual(call.inputModalities, ['text']);
const chunks = await Array.fromAsync(call.stream({ ...call.config, messages: [{ role: 'user', content: [{ type: 'text', text: 'offline' }] }], tools: [{ name: 'read', description: '', parameters: { type: 'object', required: ['path'], properties: { path: { type: 'string' } } } }] }));
const assembler = new BlockAssembler();
for (const chunk of chunks) assembler.push(chunk);
assert.equal(assembler.finish.kind, 'tool-calls');
assert.deepEqual(assembler.blocks().map(block => block.type), ['text', 'tool-call']);
assert.equal(assembler.blocks()[0].text, 'visible');
assert.equal(assembler.blocks()[1].arguments, '{"path":"a"}');
assert.equal(chunks.filter(chunk => chunk.type === 'finish').length, 1);
assert.throws(() => call.stream(call.config), /only be dispatched once/);
handle();
assert.deepEqual(llm.listProviders(), []);
assert.throws(() => handle.replace(['chatgpt-web']), /disposed/);
console.log('PASS desktop 0.2.1-rc.3 actual gate/native Config/Cordis registration-disposal/prepared dispatch/BlockAssembler; Schemastery ' + manifest('schemastery').version);

import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { hostImport } from './desktop-host.mjs';
const { Context } = await hostImport('cordis');
const { Loader } = await hostImport('cordis-plugin-loader');
const { mountRootInclude, readProfilePatches } = await hostImport('dsh-app-boot');
const { ConfigEditor } = await hostImport('dsh-config-editor');
const { SettingsForms } = await hostImport('dsh-settings');
const plugin = await import('../lib/index.js');
const dir = mkdtempSync(join(tmpdir(), 'dsh-settings-contract-'));
const ctx = new Context();
try {
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ name: 'offline-profile', private: true, dsh: { profile: { bundles: [] } } }));
  writeFileSync(join(dir, 'cordis.yml'), '[]\n');
  writeFileSync(join(dir, 'cordis.patch.yml'), JSON.stringify([{ insert: [{ id: 'dsh-chatgpt-web', name: 'cordis:chatgpt', config: {} }] }]));
  ctx.reflect.provide('profileContext', { dir, home: join(dir, 'home'), overlays: [], patchPath: join(dir, 'cordis.patch.yml'), installAnchor: join(dir, 'package.json') });
  let adapter;
  let registrations = 0;
  ctx.reflect.provide('llm', { registerAdapter(_routes, value) { registrations++; adapter = value; return () => {}; } });
  await ctx.plugin(Loader, { baseUrl: pathToFileURL(dir + '/').href });
  ctx.loader.builtins.chatgpt = plugin;
  await mountRootInclude(ctx, join(dir, 'cordis.yml'), readProfilePatches('dsh', ctx.profileContext));
  await ctx.loader.await();
  new ConfigEditor(ctx);
  const settings = new SettingsForms(ctx);
  const { TypertRegistry } = await hostImport('dsh-typert-registry');
  const { TypertGatewayService } = await hostImport('dsh-api-gateway');
  await ctx.plugin(TypertRegistry);
  let decisions = 0;
  ctx.reflect.provide('remoteAccess', { decide() { decisions++; return { kind: 'deny', reason: 'offline-deny' }; } });
  await ctx.plugin(TypertGatewayService, { websocketHeartbeatIntervalMs: 30000, streamInboxBytes: 65536 });
  const gateway = ctx.typertGateway;
  const signal = new AbortController().signal;
  const request = { namespace: 'chatGptWebStatus', method: 'status', args: {}, signal, peer: { signal, principal: { kind: 'app', id: 'offline' } } };
  await assert.rejects(gateway.prepareInvocation(request, new AbortController()), /access denied/);
  assert.equal(decisions, 1, 'real gateway applies non-owner access decisions');
  await gateway.prepareInvocation({ ...request, peer: { signal, principal: { kind: 'owner' } } }, new AbortController());
  assert.equal(decisions, 1, 'owner follows existing host owner path');
  // Prepare only: deliberately do not invoke status or read actual credentials.
  await assert.rejects(gateway.prepareInvocation({ ...request, args: { path: 'forbidden' } }, new AbortController()), /argument|field|unexpected/i);
  const before = settings.describe({ redactSecrets: true }).find(row => row.ns === 'dsh-chatgpt-web');
  assert.ok(before, 'namespace comes from real Loader/native volatile schema');
  const entry = [...ctx.loader.entries()].find(row => row.options.id === 'dsh-chatgpt-web');
  const fiber = entry.fiber;
  const original = adapter;
  await settings.update(before.ns, { minIntervalMs: 1234 }, before.revision);
  await ctx.loader.await();
  assert.equal(entry.fiber, fiber, 'volatile save preserves plugin fiber');
  assert.equal(adapter, original, 'volatile save preserves adapter and gate');
  assert.equal(registrations, 1);
  assert.equal(adapter.readConfig().minIntervalMs, 1234, 'adapter sees native saved config');
  assert.match(readFileSync(join(dir, 'cordis.patch.yml'), 'utf8'), /minIntervalMs: 1234/);
  await assert.rejects(settings.update(before.ns, { minIntervalMs: 2000 }, before.revision), /revision|conflict/i);
  ctx.loader.remove('include');
  await ctx.loader.await();
  assert.equal(settings.describe().some(row => row.ns === before.ns), false, 'unload removes namespace');
  console.log('PASS actual Loader Include / SettingsForms / ConfigEditor persistence, conflict, volatile adapter identity and disposal');
} finally {
  await ctx.fiber.dispose();
  rmSync(dir, { recursive: true, force: true });
}
